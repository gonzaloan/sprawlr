import { useEffect, useRef, useState } from "react";
import { marked } from "marked";
import DOMPurify from "dompurify";
import type { DocFile } from "../types";

interface Props {
  docs: DocFile[] | null; // null = not available for this source
  path: string;
  onNavigate: (path: string) => void;
  actions: React.ReactNode;
}

let mermaidReady: Promise<typeof import("mermaid").default> | null = null;
function loadMermaid() {
  // Loaded only when documentation is opened; it is the heaviest dependency.
  mermaidReady ??= import("mermaid").then(({ default: m }) => {
    m.initialize({
      startOnLoad: false,
      securityLevel: "strict",
      theme: "base",
      fontFamily: "Barlow, system-ui, sans-serif",
      themeVariables: {
        fontSize: "14px",
        primaryColor: "#f6f8f3",
        primaryBorderColor: "#1d2b2a",
        primaryTextColor: "#1d2b2a",
        lineColor: "#4a5a55",
        clusterBkg: "#e3e9e2",
        clusterBorder: "#5d7a63",
        edgeLabelBackground: "#f6f8f3",
        tertiaryColor: "#f6f8f3",
      },
      flowchart: { curve: "basis", padding: 12, nodeSpacing: 36, rankSpacing: 56, useMaxWidth: false },
    });
    return m;
  });
  return mermaidReady;
}

let seq = 0;

export function DocsView({ docs, path, onNavigate, actions }: Props) {
  const ref = useRef<HTMLDivElement>(null);
  const [error, setError] = useState<string | null>(null);
  const doc = docs?.find((d) => d.path === path) ?? docs?.[0];

  useEffect(() => {
    const el = ref.current;
    if (!el || !doc) return;
    let live = true;
    setError(null);
    // Resource names and tag values come from the AWS account: sanitize before rendering.
    el.innerHTML = DOMPurify.sanitize(marked.parse(doc.content, { async: false }) as string);
    const blocks = [...el.querySelectorAll<HTMLElement>("pre > code.language-mermaid")];
    if (blocks.length) {
      loadMermaid()
        .then(async (m) => {
          for (const code of blocks) {
            if (!live) return;
            const { svg } = await m.render(`mmd-${++seq}`, code.textContent ?? "");
            const fig = document.createElement("figure");
            fig.className = "doc__diagram";
            fig.title = "Click to switch between fitted and full size";
            fig.innerHTML = svg; // produced by mermaid with securityLevel "strict"
            code.parentElement?.replaceWith(fig);
          }
        })
        .catch((e) => live && setError(`A diagram could not be drawn: ${e instanceof Error ? e.message : e}`));
    }
    return () => {
      live = false;
    };
  }, [doc]);

  // Links between pages (README.md → apps/x.md) stay inside the app.
  const onClick = (e: React.MouseEvent) => {
    const fig = (e.target as HTMLElement).closest(".doc__diagram");
    if (fig) return void fig.classList.toggle("is-full");
    const a = (e.target as HTMLElement).closest("a");
    const href = a?.getAttribute("href");
    if (!href || /^[a-z]+:/i.test(href)) return;
    e.preventDefault();
    const base = path.includes("/") ? path.slice(0, path.lastIndexOf("/") + 1) : "";
    const target = href.startsWith("../") ? href.slice(3) : base + href;
    onNavigate(docs?.some((d) => d.path === href) ? href : target);
  };

  if (!docs)
    return (
      <div className="empty">
        <p>Documentation is generated by the desktop app, or with <code>sprawlr docs --snapshot file.json</code>.</p>
      </div>
    );

  return (
    <div className="docs">
      <div className="docs__bar">
        <span className="muted">
          {doc?.path} {docs.length > 1 && `(${docs.length} pages)`}
        </span>
        <span className="docs__actions">{actions}</span>
      </div>
      {error && (
        <p className="scan__msg" role="alert">
          {error}
        </p>
      )}
      <article className="doc" ref={ref} onClick={onClick} />
    </div>
  );
}
